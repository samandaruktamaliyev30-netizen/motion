import json,sys
FPS=30
SEG=[(0.00,2.50),(2.62,3.90),(4.08,4.80),(5.20,10.95),'MOVIE',(32.05,34.36),(34.98,35.76),(35.98,36.45),(37.18,44.24),(44.64,51.24),(52.46,54.30),'DRONE']
MOVIE=480; DRONE=112
clips=[]; out=0; marks={}
for s in SEG:
    if s=='MOVIE': marks['movie']=(out,out+MOVIE); out+=MOVIE; continue
    if s=='DRONE': marks['drone']=(out,out+DRONE); out+=DRONE; continue
    a,b=round(s[0]*FPS),round(s[1]*FPS); clips.append((a,b,out)); out+=b-a
DUR=out
def at(t):
    f=round(t*FPS)
    for a,b,o in clips:
        if a<=f<=b: return o+f-a
    for a,b,o in clips:
        if f<a: return o
    raise Exception(t)
